"""Markdown data report for a public dataset (``docs/data/<name>.md``).

Generated from the artefacts of each stage, so the numbers in the document
are exactly what the pipeline measured.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import numpy as np

from fraudx.datasets.base import read_json
from fraudx.datasets.info import DatasetInfo
from fraudx.ml.dataset import matrix_path
from fraudx.ml.report import prevalence_table


def _row(cells: list[Any]) -> str:
    return "| " + " | ".join(str(c).replace("|", "\\|") for c in cells) + " |"


def _table(header: list[str], rows: list[list[Any]]) -> list[str]:
    return [_row(header), _row(["---"] * len(header)), *(_row(r) for r in rows)]


def _fmt(n: Any) -> str:
    return f"{n:,}" if isinstance(n, int) else str(n)


DETECTORS = {
    "fraud_lgbm": "supervised (LightGBM, transaction features)",
    "anomaly_iforest": "anomaly (Isolation Forest, legitimate traffic)",
    "graph_lgbm": "graph (LightGBM, graph features)",
}


def _latest_model(
    models_dir: Path, dataset_dir: Path, name: str = "fraud_lgbm"
) -> dict[str, Any] | None:
    """The most recent model ``name`` trained on ``dataset_dir``."""
    found = []
    for meta in models_dir.glob(f"{name}/*/metadata.json"):
        data = json.loads(meta.read_text(encoding="utf-8"))
        if Path(data["data"]["dataset"]) == dataset_dir:
            found.append(data)
    return max(found, key=lambda d: d["trained_at"]) if found else None


def render(info: DatasetInfo, out_dir: Path, models_dir: Path = Path("models")) -> str:
    profile = read_json(out_dir / "profile.json")
    cleaning = read_json(out_dir / "cleaning_report.json")
    raw_files = read_json(out_dir / "raw_files.json")["files"]
    summary = read_json(out_dir / "summary.json") if (out_dir / "summary.json").exists() else None

    lines = [
        f"# Dataset: {info.title}",
        "",
        f"> Generated by `python -m fraudx.datasets {info.name}` from the pipeline's "
        "own artefacts. Do not edit by hand.",
        "",
        "## 1. Source and licence",
        "",
        f"- **Source:** [{info.kaggle_ref}]({info.source_url})",
        f"- **Licence:** {info.license}. Attribution required; derived data shares the "
        "same licence. Raw and processed data are git-ignored, not redistributed.",
        f"- **Citation:** {info.citation}",
        "",
        *_table(
            ["raw file", "bytes", "sha256"],
            [[f["name"], _fmt(f["bytes"]), f"`{f['sha256'][:16]}…`"] for f in raw_files],
        ),
        "",
        "## 2. Pipeline",
        "",
        "```text",
        "raw CSV ─► 1 profile ─► 2 clean ─► 3 canonicalize ─► 4 features ─► 5 train",
        "           profile.json  cleaning_report.json  enriched_transactions.jsonl",
        "                         cleaned.parquet       ground_truth.csv, summary.json",
        "```",
        "",
        f"Outputs: `{out_dir}/`. Reproduce with `make {info.name.replace('_', '-')}`.",
        "",
        "## 3. Raw data profile",
        "",
    ]
    scalar = {k: v for k, v in profile.items() if not isinstance(v, (dict, list))}
    lines += _table(["measure", "value"], [[k, _fmt(v)] for k, v in scalar.items()])
    for key, value in profile.items():
        if isinstance(value, dict):
            lines += ["", f"**{key}**", ""]
            flat = {k: v for k, v in value.items() if not isinstance(v, list)}
            lines += _table(["measure", "value"], [[k, _fmt(v)] for k, v in flat.items()])
            for sub, records in value.items():
                if isinstance(records, list) and records and isinstance(records[0], dict):
                    lines += ["", f"*{key}.{sub}*", ""]
                    lines += _table(
                        list(records[0]), [[_fmt(v) for v in r.values()] for r in records]
                    )
        elif isinstance(value, list) and value and isinstance(value[0], dict):
            lines += ["", f"**{key}**", ""]
            lines += _table(list(value[0]), [[_fmt(v) for v in r.values()] for r in value])

    lines += [
        "",
        "## 4. Cleaning",
        "",
        f"Rows {cleaning['rows_in']:,} → **{cleaning['rows_out']:,}**; positive labels "
        f"{cleaning['positives_in']:,} → **{cleaning['positives_out']:,}**.",
        "Actions: `drop_rows` removes rows, `drop_column` removes a column, `transform` "
        "changes values, `flag` documents an issue that is kept on purpose.",
        "",
        *_table(
            ["#", "rule", "action", "rows", "positives", "rationale"],
            [
                [
                    i,
                    f"`{r['rule']}`",
                    r["action"],
                    _fmt(r["rows_affected"]),
                    _fmt(r["positives_affected"]),
                    r["rationale"],
                ]
                for i, r in enumerate(cleaning["rules"], 1)
            ],
        ),
    ]
    if fx := cleaning["notes"].get("fx_usd_per_unit"):
        lines += ["", "Derived FX rates (USD per unit):", ""]
        lines += _table(
            ["currency", "USD per unit"], [[c, f"{v:.6g}"] for c, v in sorted(fx.items())]
        )

    lines += [
        "",
        "## 5. Mapping to the platform contract (`TransactionEvent` v1)",
        "",
        *_table(["raw", "canonical", "transformation"], [list(m) for m in info.mapping]),
    ]
    if summary:
        lines += [
            "",
            f"Canonical dataset: **{summary['events']:,}** events, "
            f"{summary['fraud_events']:,} positive ({summary['fraud_rate']:.4%}), "
            f"{summary['first_event']} → {summary['last_event']}.",
            "",
            *_table(
                ["scenario", "events"], [[k, _fmt(v)] for k, v in summary["by_scenario"].items()]
            ),
        ]

    lines += ["", "## 6. Feature engineering", ""]
    features = matrix_path(out_dir)
    if features.exists():
        with np.load(features, allow_pickle=False) as data:
            X, names = data["X"], [str(n) for n in data["feature_names"]]
            coverage = 1 - np.isnan(X).mean(axis=0)
            # Strided sample over the whole period (the first rows cover only a few hours).
            sample = X[:: max(1, len(X) // 200_000)]
            distinct = [
                len(np.unique(sample[~np.isnan(sample[:, i]), i])) for i in range(len(names))
            ]
        lines += [
            "Features are computed by the platform's **online** feature code "
            "(`OnlineFeatureStore`, Redis Lua) replayed in event-time order on a disposable "
            "Redis, so training features are identical to what the live pipeline computes.",
            "Coverage = share of rows where the feature has a value; a feature with one "
            "distinct value carries no information on this dataset.",
            "",
            *_table(
                ["feature", "coverage", "distinct values (sample)"],
                [[n, f"{c:.1%}", d] for n, c, d in zip(names, coverage, distinct, strict=True)],
            ),
        ]
    else:
        lines.append(f"_Not built yet: `python -m fraudx.ml build-features --dataset {out_dir}`._")

    lines += ["", "## 7. Model results", ""]
    model = _latest_model(models_dir, out_dir)
    if model:
        m = model["metrics"]
        lines += [
            f"Model `{model['name']}:{model['version']}` (LightGBM; time-based 70/15/15 split; "
            f"threshold {model['threshold']:.4f} chosen on validation).",
            "",
            *_table(
                ["set", "rows", "positives", "PR-AUC", "ROC-AUC", "precision", "recall", "F1"],
                [
                    [
                        k,
                        _fmt(m[k]["n"]),
                        _fmt(m[k]["positives"]),
                        m[k]["pr_auc"],
                        m[k]["roc_auc"],
                        m[k]["precision"],
                        m[k]["recall"],
                        m[k]["f1"],
                    ]
                    for k in ("valid", "test")
                    if k in m
                ],
            ),
            "",
            *prevalence_table({k: m[k] for k in ("valid", "test") if k in m}),
            "Ablations (test PR-AUC without a feature group):",
            "",
            *_table(
                ["variant", "PR-AUC"],
                [
                    ["full model", m["test"]["pr_auc"]],
                    *[[k, v["test_pr_auc"]] for k, v in model["ablations"].items()],
                ],
            ),
            "",
            "Top features (gain share): "
            + ", ".join(f"`{n}` {g:.0%}" for n, g in model["importance"][:6]),
        ]
        if by := m["test"].get("by_scenario"):
            lines += [
                "",
                *_table(
                    ["scenario (test)", "rows", "recall / FPR"],
                    [
                        [k, _fmt(v["n"]), v.get("recall", v.get("false_positive_rate"))]
                        for k, v in by.items()
                    ],
                ),
            ]
    else:
        lines.append("_No model trained on this dataset yet._")

    detectors = {n: m for n in DETECTORS if (m := _latest_model(models_dir, out_dir, n))}
    if len(detectors) > 1:
        lines += [
            "",
            "Detectors trained on this dataset (test set; matched = at the dataset's fraud rate):",
            "",
            *_table(
                ["detector", "model", "PR-AUC", "PR-AUC matched", "ROC-AUC"],
                [
                    [
                        DETECTORS[n],
                        f"`{m['version']}`",
                        m["metrics"]["test"]["pr_auc"],
                        m["metrics"]["test"].get("at_reference_prevalence", {}).get("pr_auc", "-"),
                        m["metrics"]["test"]["roc_auc"],
                    ]
                    for n, m in detectors.items()
                ],
            ),
        ]

    lines += ["", "## 8. Limitations", "", *(f"- {item}" for item in info.limitations), ""]
    return "\n".join(lines)
